#!/usr/bin/env python3
"""Encodes GoldenEye's animation clips as `GEAN` resources (frigate issue
#73). Payload: docs/formats/goldeneye-animation-clip-resource.md.

A clip's header fields (frame count, angle bit width, frame size) are
already reachable as plain C source, the same way ge_skeleton.py reads a
skeleton's `JOINTLIST` -- `assets/animationtable_data.c` compiles each
clip's `ModelAnimation` header as a `u32 ANIM_DATA_<name>[]` array (the
GoldenEye decomp's own comment notes the rest of that array's words are a
placeholder, "until autogenerated", not real frame data).

The actual per-frame bitstream is not decompiled to source at all: it is
raw ROM bytes in `assets/animationtable_entries.bin`, one contiguous region
per clip at the byte offset `assets/animationtable_entries.h`'s
`PTR_ANIM_ENTRY_<name>` names, extracted from the user's own ROM by the
GoldenEye decomp's own tooling (the same `extract_files` step
pack_model_resources.py's callers already run for model files) -- reusing
that existing extraction, not reimplementing it.
"""

from __future__ import annotations

import re
import struct
from pathlib import Path
from typing import Dict, NamedTuple, Union

_ANIM_HEADER_RE = re.compile(r"u32\s+ANIM_DATA_(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\};", re.S)
_ENTRY_OFFSET_RE = re.compile(r"#define\s+PTR_ANIM_ENTRY_(\w+)\s+(0[xX][0-9a-fA-F]+|\d+)")

_HEADER_STRUCT = struct.Struct(">IBBHI")
HEADER_SIZE = _HEADER_STRUCT.size

ANIMATION_CLIP_RESOURCE_TYPE = "GEAN"
ANIMATION_CLIP_RESOURCE_VERSION = 0


class AnimationClip(NamedTuple):
    frame_count: int
    angle_width_bits: int
    loop: bool
    frame_size_bytes: int
    bitstream: bytes


def parse_animations(decomp_dir: Union[str, Path]) -> Dict[str, AnimationClip]:
    """Every animation clip, keyed by its `ANIM_DATA_<name>`/
    `PTR_ANIM_ENTRY_<name>` name with the prefix stripped. Requires
    `assets/animationtable_entries.bin` to already be extracted from a ROM
    (the GoldenEye decomp's "files" extraction mode)."""
    decomp_dir = Path(decomp_dir)
    header_text = (decomp_dir / "assets" / "animationtable_data.c").read_text()
    entries_text = (decomp_dir / "assets" / "animationtable_entries.h").read_text()
    blob = (decomp_dir / "assets" / "animationtable_entries.bin").read_bytes()

    offsets = {match.group(1): int(match.group(2), 0) for match in _ENTRY_OFFSET_RE.finditer(entries_text)}

    clips: Dict[str, AnimationClip] = {}
    for match in _ANIM_HEADER_RE.finditer(header_text):
        name, body = match.group(1), match.group(2)
        words = [token.strip() for token in body.split(",") if token.strip()]

        header_word1 = int(words[1], 0)
        frame_count = (header_word1 >> 16) & 0xFFFF
        angle_width_bits = (header_word1 >> 8) & 0xFF
        loop = bool(header_word1 & 1)

        header_word3 = int(words[3], 0)
        frame_size_bytes = (header_word3 & 0xFFFF) // 8

        offset = offsets.get(name, 0)
        size = frame_count * frame_size_bytes
        bitstream = blob[offset : offset + size]

        clips[name] = AnimationClip(frame_count, angle_width_bits, loop, frame_size_bytes, bitstream)
    return clips


def encode_animation_clip_payload(clip: AnimationClip) -> bytes:
    header = _HEADER_STRUCT.pack(clip.frame_count, clip.angle_width_bits, 1 if clip.loop else 0, 0,
                                 clip.frame_size_bytes)
    return header + clip.bitstream
