#!/usr/bin/env python3
"""Regenerates src/extract/ModelTablesData.cpp from a GoldenEye decomp checkout.

    tools/gen_model_tables.py [--decomp external/007] [--output src/extract/ModelTablesData.cpp]

Reads the MODELFILEHEADER tables under assets/obseg (switch and texture counts, skeleton name, bounding volume
radius of every chr/gun/prop model) and the JOINTLIST arrays under assets/embedded/skeletons, with the same readers
tools/o2r_packer uses (ge_model.read_model_header_counts, ge_skeleton.parse_skeletons), and emits them as plain
tables. The decomp is only needed to regenerate; the generated file is committed, so building needs no checkout.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "o2r_packer"))

from ge_model import read_model_header_counts  # noqa: E402
from ge_skeleton import parse_skeletons  # noqa: E402


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--decomp", default="external/007", type=Path)
    parser.add_argument("--output", default="src/extract/ModelTablesData.cpp", type=Path)
    args = parser.parse_args()

    counts = read_model_header_counts(args.decomp)
    skeletons = parse_skeletons(args.decomp)

    out = [
        "// Generated by tools/gen_model_tables.py from the GoldenEye decomp's MODELFILEHEADER tables and skeleton",
        "// JOINTLIST arrays. Do not edit by hand.",
        "",
        "// clang-format off",
        "",
        '#include "extract/ModelTables.h"',
        "",
        "namespace Frigate::Extract::Detail {",
        "",
        "// {header name, switches, textures, skeleton, bounding volume radius}, sorted by name. The skeleton is empty",
        "// for a model with none.",
        "const ModelHeaderEntry kModelHeaders[] = {",
    ]
    for name in sorted(counts):
        c = counts[name]
        out.append(f'    {{"{name}", {c.num_switches}, {c.num_textures}, "{c.skeleton_name or ""}", {c.radius!r}}},')
    out.append("};")
    out.append("const size_t kModelHeaderCount = sizeof(kModelHeaders) / sizeof(kModelHeaders[0]);")
    out.append("")
    out.append("// {node type, matrix a, matrix b} of every joint of every skeleton, in skeleton order.")
    out.append("const SkeletonJoint kSkeletonJoints[] = {")
    entries = []
    at = 0
    for name in sorted(skeletons):
        joints = skeletons[name]
        entries.append((name, at, len(joints)))
        out.append(f"    // {name}")
        for joint in joints:
            out.append(f"    {{{joint.node_type}, {joint.mtx_a}, {joint.mtx_b}}},")
        at += len(joints)
    out.append("};")
    out.append("")
    out.append("// {skeleton name, first joint, joint count}, sorted by name.")
    out.append("const SkeletonEntry kSkeletons[] = {")
    for name, first, count in entries:
        out.append(f'    {{"{name}", {first}, {count}}},')
    out.append("};")
    out.append("const size_t kSkeletonCount = sizeof(kSkeletons) / sizeof(kSkeletons[0]);")
    out.append("")
    out.append("}  // namespace Frigate::Extract::Detail")
    out.append("// clang-format on")
    out.append("")
    args.output.write_text("\n".join(out))


if __name__ == "__main__":
    main()
