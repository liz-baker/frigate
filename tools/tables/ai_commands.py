"""The AI list command opcodes (AI_CMD) and the byte layout of each command's record (the `Ai*Record` structs,
packed one byte apart), read from the GoldenEye decomp by running its preprocessor over chraidata.c, as
src/level/AiCommands.h.

The decomp's identifiers are kept so the interpreter in src/level/ChrAi.cpp can be read against chrai.c.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path
from typing import Dict, List, Tuple

from .common import Output

_SIZES = {"u8": 1, "s8": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "f32": 4}


def run_preprocessor(decomp_dir: Path) -> str:
    """The decomp's chraidata.c after the C preprocessor. The decomp's
    headers have a stray token paste that makes the preprocessor exit
    non-zero after it has written everything, so the status is ignored."""
    result = subprocess.run(
        [
            "gcc", "-E", "-P", "-I.", "-Iinclude", "-Isrc", "-Isrc/game",
            "-D_LANGUAGE_C", "src/game/chraidata.c",
        ],
        cwd=decomp_dir,
        capture_output=True,
        text=True,
        check=False,
    )
    if "AI_CMD_COUNT" not in result.stdout:
        raise RuntimeError("preprocessing chraidata.c produced no AI_CMD enum:\n" + result.stderr[-2000:])
    return result.stdout


def parse_commands(text: str) -> List[str]:
    match = re.search(r"typedef enum AI_CMD\s*\{(.*?)\}\s*AI_CMD;", text, re.S)
    if match is None:
        raise RuntimeError("no AI_CMD enum")
    names: List[str] = []
    for item in match.group(1).split(","):
        item = item.strip()
        if not item:
            continue
        if "=" in item:
            raise RuntimeError(f"AI_CMD has an explicit value: {item}")
        if item != "AI_CMD_COUNT":
            names.append(item)
    return names


def parse_records(text: str, commands: List[str]) -> Dict[str, List[Tuple[str, int, int, str]]]:
    """Command name -> [(field, offset, size, type)]; the record's size is the
    end of its last field."""
    wanted = {"Ai" + name[3:] + "Record": name for name in commands}
    records: Dict[str, List[Tuple[str, int, int]]] = {}
    for record, body in re.findall(r"typedef struct (Ai\w+Record)\s*\{(.*?)\}\s*\1;", text, re.S):
        name = wanted.get(record)
        if name is None:
            continue
        fields: List[Tuple[str, int, int, str]] = []
        offset = 0
        for line in body.split(";"):
            line = line.strip()
            if not line:
                continue
            match = re.fullmatch(r"(u8|s8|u16|s16|u32|s32|f32)\s+(\w+)(?:\[(\d*)\])?", line)
            if match is None:
                raise RuntimeError(f"{record}: unsupported field `{line}`")
            kind, field, count = match.group(1), match.group(2), match.group(3)
            if count == "":
                # A flexible array ends the record; only AI_PRINT has one.
                fields.append((field, offset, 0, kind))
                break
            size = _SIZES[kind] * (int(count) if count else 1)
            fields.append((field, offset, size, kind if count is None else f"{kind}[{count}]"))
            offset += size
        records[name] = fields
    return records


def render(commands: List[str], records: Dict[str, List[Tuple[str, int, int, str]]]) -> str:
    out: List[str] = []
    out.append("// Generated by tools/gen_tables.py from the GoldenEye decomp's AI command definitions. Do not edit by hand;")
    out.append("// regenerate with `just gen-tables`.")
    out.append("")
    out.append("// clang-format off")
    out.append("#pragma once")
    out.append("")
    out.append("#include <array>")
    out.append("#include <cstddef>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace Frigate::Level {")
    out.append("")
    out.append("// AI_CMD: the first byte of each command in an AI list.")
    out.append("enum AiCmd : uint8_t {")
    for name in commands:
        out.append(f"    {name},")
    out.append("};")
    out.append("")
    out.append(f"constexpr size_t kAiCommandCount = {len(commands)};")
    out.append("")
    out.append("// The byte layout of each command: its size (sizeof the decomp's packed Ai*Record)")
    out.append("// and its fields' offsets, with the field's C type after each (the decomp reads")
    out.append("// a field as that type, which matters for the signed special ids). AI_PRINT has")
    out.append("// no fixed size (a C string follows the opcode), so its kSize is the opcode alone.")
    for name in commands:
        fields = records.get(name)
        if fields is None:
            raise RuntimeError(f"no record for {name}")
        size = max((o + s for _, o, s, _ in fields), default=0)
        out.append(f"struct Ai{name[3:]}Record {{")
        out.append(f"    static constexpr size_t kSize = {size};")
        for field, offset, _, kind in fields:
            if field == "cmd":
                continue
            out.append(f"    static constexpr size_t {field} = {offset}; // {kind}")
        out.append("};")
    out.append("")
    out.append("// chraiitemsize for a command other than AI_PRINT; 1 for an unknown opcode.")
    out.append("constexpr std::array<uint8_t, 256> MakeAiCommandSizes() {")
    out.append("    std::array<uint8_t, 256> sizes{};")
    out.append("    for (auto& size : sizes) {")
    out.append("        size = 1;")
    out.append("    }")
    for name in commands:
        out.append(f"    sizes[{name}] = Ai{name[3:]}Record::kSize;")
    out.append("    return sizes;")
    out.append("}")
    out.append("inline constexpr std::array<uint8_t, 256> kAiCommandSizes = MakeAiCommandSizes();")
    out.append("")
    out.append("} // namespace Frigate::Level")
    out.append("// clang-format on")
    out.append("")
    return "\n".join(out)


def generate_ai_commands(decomp_dir: Path) -> Output:
    text = run_preprocessor(decomp_dir)
    commands = parse_commands(text)
    return Output("src/level/AiCommands.h", render(commands, parse_records(text, commands)))
