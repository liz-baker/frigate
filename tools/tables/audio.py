"""The sound effect and music track names (src/extract/AudioNamesData.cpp)."""

from __future__ import annotations

from .common import Decomp, Output, TableError, banner, enum_entries, footer

ENUMS = (("SFX_ID", "kSfxNames"), ("MUSIC_TRACKS", "kMusicNames"))


def generate_audio_names(decomp: Decomp) -> Output:
    header_text = decomp.read("src/bondconstants.h")
    out = banner("the GoldenEye decomp's SFX_ID and MUSIC_TRACKS enums in src/bondconstants.h")
    out += ['#include "extract/AudioNames.h"', "", "namespace Frigate::Extract::Detail {", ""]
    for enum_name, symbol in ENUMS:
        try:
            entries = enum_entries(header_text, enum_name)
        except ValueError as error:
            raise TableError(f"{enum_name}: {error}") from error
        out.append(f"// {enum_name}: {{name, value}}")
        out.append(f"const AudioName {symbol}[] = {{")
        for name, value in entries:
            out.append(f'    {{"{name}", {value}}},')
        out.append("};")
        out.append(f"const size_t {symbol}Count = sizeof({symbol}) / sizeof({symbol}[0]);")
        out.append("")
    out += ["}  // namespace Frigate::Extract::Detail"] + footer()
    return Output("src/extract/AudioNamesData.cpp", "\n".join(out))


def sfx_constant(name: str) -> str:
    """`GUN_RIFLE7BIG_1_SFX` becomes `kSfxGunRifle7big1`."""
    if name.endswith("_SFX"):
        name = name[: -len("_SFX")]
    return "kSfx" + "".join(part.capitalize() for part in name.split("_"))


def generate_sfx_ids(decomp: Decomp) -> Output:
    """src/audio/SfxIds.h: the SFX_ID enum as C++ constants, numbered by the sound's index in the sound-effect bank."""
    try:
        entries = enum_entries(decomp.read("src/bondconstants.h"), "SFX_ID")
    except ValueError as error:
        raise TableError(f"SFX_ID: {error}") from error
    seen = {}
    lines = []
    for index, (name, value) in enumerate(entries):
        if value != index:
            raise TableError(f"SFX_ID {name} is {value}, not its position {index}; the bank is indexed by position")
        ident = sfx_constant(name)
        if ident in seen:
            raise TableError(f"{name} and {seen[ident]} both map to {ident}")
        seen[ident] = name
        lines.append(f"    {ident} = {index},")
    out = [
        "// Generated by tools/gen_tables.py from the GoldenEye decomp's SFX_ID enum. Do not edit by hand; regenerate",
        "// with `just gen-tables`.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace Frigate::AudioDriver {",
        "",
        "// SFX_ID: the sound-effect numbers the game plays sounds by (0 is no sound).",
        "enum SfxId : int16_t {",
        *lines,
        f"    kSfxCount = {len(entries)},",
        "};",
        "",
        "} // namespace Frigate::AudioDriver",
        "",
    ]
    return Output("src/audio/SfxIds.h", "\n".join(out))
