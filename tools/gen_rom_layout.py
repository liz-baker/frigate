#!/usr/bin/env python3
"""Regenerates src/extract/RomLayoutData.cpp and src/extract/ImageDefData.cpp from a GoldenEye decomp checkout.

    tools/gen_rom_layout.py [--decomp external/007] [--output src/extract/RomLayoutData.cpp]
                            [--defs-output src/extract/ImageDefData.cpp] [--hit-types src/extract/ImageDefs.h]

Reads scripts/filelist.{u,e,j}.csv and imagelist.u.csv and emits them as
plain offset/size/name tables, and assets/images.def as a table of image
names, hit surface types and detail-tile fields. The decomp is only needed to
regenerate; the generated files are committed, so building needs no decomp
checkout.
"""

import argparse
import csv
import re
from pathlib import Path

REGIONS = (("u", "Us"), ("e", "Eur"), ("j", "Jp"))


def read_rows(path):
    with open(path, newline="") as f:
        return [row for row in csv.reader(f) if row]


def file_rows(decomp, code):
    rows = []
    for offset, size, name, compressed, extract in read_rows(decomp / "scripts" / f"filelist.{code}.csv"):
        rows.append((int(offset), int(size), name, int(compressed), int(extract)))
    return rows


def hit_type_names(bondconstants):
    """The HIT_TYPE enumerators of src/bondconstants.h, in order, without the trailing count."""
    match = re.search(r"typedef\s+enum\s+HIT_TYPE\s*\{(.*?)\}\s*HIT_TYPE\s*;", bondconstants.read_text(), re.S)
    names = [item.strip() for item in match.group(1).split(",") if item.strip()]
    return [name for name in names if name != "HIT_TYPE_COUNT"]


def header_hit_types(header):
    """The HitType enumerators declared in src/extract/ImageDefs.h."""
    match = re.search(r"enum HitType[^{]*\{(.*?)\};", header.read_text(), re.S)
    return [item.strip() for item in match.group(1).split(",") if item.strip()]


def image_def_rows(images_def):
    """(name, hit sound, hit impact, [detail fields]) of every IMAGE() line, in file order. The IMAGE() parsing is
    adapted from goldeneye-pc-port's generate_imagelist.py (MIT); see THIRD_PARTY_LICENSES.md."""
    rows = []
    for line in images_def.read_text().splitlines():
        line = line.strip()
        if not line.startswith("IMAGE("):
            continue
        close = line.find(")")
        parts = [p.strip() for p in line[len("IMAGE("):close if close >= 0 else len(line)].split(",")]
        if len(parts) < 4:
            continue
        detail = [0, 0, 0, 0]
        if len(parts) >= 8:
            detail = [int(f, 16) if f.lower().startswith("0x") else int(f) for f in parts[4:8]]
            detail = [value & 0xF for value in detail]
        rows.append((parts[0], parts[2], parts[3], detail))
    return rows


def write_image_defs(args, image_count):
    known = hit_type_names(args.decomp / "src" / "bondconstants.h")
    declared = header_hit_types(args.hit_types)
    if known != declared:
        raise SystemExit(f"{args.hit_types} lists HitType {declared}, but the decomp's HIT_TYPE is {known}")
    rows = image_def_rows(args.decomp / "assets" / "images.def")
    if len(rows) > image_count:
        raise SystemExit(f"images.def has {len(rows)} images but imagelist.u.csv only {image_count}")
    out = [
        "// Generated by tools/gen_rom_layout.py from the GoldenEye decomp's assets/images.def. Do not edit by hand;",
        "// regenerate with `python3 tools/gen_rom_layout.py` (needs external/007).",
        "",
        "// clang-format off",
        "",
        '#include "extract/ImageDefs.h"',
        "",
        "namespace Frigate::Extract::Detail {",
        "",
        "// {name, hit sound, hit impact, {detail fields}}, in images.def order.",
        "const ImageDef kImageDefs[] = {",
    ]
    for name, sound, impact, detail in rows:
        if sound not in known or impact not in known:
            raise SystemExit(f"image {name} has the unknown surface type {sound} / {impact}")
        out.append(f'    {{"{name}", {sound}, {impact}, {{{", ".join(str(v) for v in detail)}}}}},')
    out.append("};")
    out.append("const size_t kImageDefCount = sizeof(kImageDefs) / sizeof(kImageDefs[0]);")
    out.append("")
    out.append("}  // namespace Frigate::Extract::Detail")
    out.append("// clang-format on")
    out.append("")
    args.defs_output.write_text("\n".join(out))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--decomp", default="external/007", type=Path)
    parser.add_argument("--output", default="src/extract/RomLayoutData.cpp", type=Path)
    parser.add_argument("--defs-output", default="src/extract/ImageDefData.cpp", type=Path)
    parser.add_argument("--hit-types", default="src/extract/ImageDefs.h", type=Path)
    args = parser.parse_args()

    out = [
        "// Generated by tools/gen_rom_layout.py from the GoldenEye decomp's",
        "// scripts/filelist.{u,e,j}.csv and imagelist.u.csv. Do not edit by hand.",
        "",
        "// clang-format off",
        "",
        '#include "extract/RomLayout.h"',
        "",
        "namespace Frigate::Extract::Detail {",
        "",
    ]
    for code, name in REGIONS:
        out.append(f"// {{offset, size, name, compressed, extract}}")
        out.append(f"const FileEntry k{name}Files[] = {{")
        for offset, size, path, compressed, extract in file_rows(args.decomp, code):
            out.append(f'    {{{offset}, {size}, "{path}", {"true" if compressed else "false"}, {"true" if extract else "false"}}},')
        out.append("};")
        out.append(f"const size_t k{name}FileCount = sizeof(k{name}Files) / sizeof(k{name}Files[0]);")
        out.append("")

    out.append("// US ROM offsets; Europe and Japan shift them (see RomLayout.h).")
    out.append("// {offset, size}, indexed like images.def.")
    out.append("const ImageEntry kImages[] = {")
    for offset, size, *_ in read_rows(args.decomp / "imagelist.u.csv"):
        out.append(f"    {{{int(offset)}, {int(size)}}},")
    out.append("};")
    out.append("const size_t kImageCount = sizeof(kImages) / sizeof(kImages[0]);")
    out.append("")
    out.append("}  // namespace Frigate::Extract::Detail")
    out.append("// clang-format on")
    out.append("")
    args.output.write_text("\n".join(out))
    write_image_defs(args, len(read_rows(args.decomp / "imagelist.u.csv")))


if __name__ == "__main__":
    main()
