#!/usr/bin/env python3
"""Regenerates src/extract/AudioNamesData.cpp from a GoldenEye decomp checkout.

    tools/gen_audio_tables.py [--decomp external/007] [--output src/extract/AudioNamesData.cpp]

Reads the SFX_ID and MUSIC_TRACKS enums in src/bondconstants.h and emits their
{name, value} pairs. The decomp is only needed to regenerate; the generated
file is committed, so building and extracting need no decomp checkout.
"""

import argparse
import re
from pathlib import Path

ENUMS = (("SFX_ID", "kSfxNames"), ("MUSIC_TRACKS", "kMusicNames"))

COMMENTS = re.compile(r"//[^\n]*|/\*.*?\*/", re.DOTALL)


def parse_enum(header_text, enum_name):
    """(name, value) for each entry of `typedef enum <enum_name> {...} <enum_name>;`."""
    match = re.search(r"typedef\s+enum\s+" + enum_name + r"\s*\{(.*?)\}\s*" + enum_name + r"\s*;", header_text, re.DOTALL)
    if match is None:
        raise SystemExit(f"no {enum_name} enum in the header")
    entries = []
    value = 0
    for entry in COMMENTS.sub("", match.group(1)).split(","):
        entry = entry.strip()
        if not entry:
            continue
        name, _, assigned = (part.strip() for part in entry.partition("="))
        if assigned:
            try:
                value = int(assigned, 0)
            except ValueError:
                raise SystemExit(f"{enum_name} entry {name} has a value that is not a number: {assigned!r}")
        entries.append((name, value))
        value += 1
    return entries


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--decomp", default="external/007", type=Path)
    parser.add_argument("--output", default="src/extract/AudioNamesData.cpp", type=Path)
    args = parser.parse_args()

    header_text = (args.decomp / "src" / "bondconstants.h").read_text()
    out = [
        "// Generated by tools/gen_audio_tables.py from the GoldenEye decomp's SFX_ID and MUSIC_TRACKS enums in",
        "// src/bondconstants.h. Do not edit by hand; regenerate with",
        "//     tools/gen_audio_tables.py --decomp external/007",
        "",
        "// clang-format off",
        "",
        '#include "extract/AudioNames.h"',
        "",
        "namespace Frigate::Extract::Detail {",
        "",
    ]
    for enum_name, symbol in ENUMS:
        entries = parse_enum(header_text, enum_name)
        out.append(f"// {enum_name}: {{name, value}}")
        out.append(f"const AudioName {symbol}[] = {{")
        for name, value in entries:
            out.append(f'    {{"{name}", {value}}},')
        out.append("};")
        out.append(f"const size_t {symbol}Count = sizeof({symbol}) / sizeof({symbol}[0]);")
        out.append("")
    out.append("}  // namespace Frigate::Extract::Detail")
    out.append("// clang-format on")
    out.append("")
    args.output.write_text("\n".join(out))


if __name__ == "__main__":
    main()
