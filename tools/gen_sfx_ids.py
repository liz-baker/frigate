#!/usr/bin/env python3
"""Writes src/audio/SfxIds.h: the decomp's SFX_ID enum as C++ constants.

    python3 tools/gen_sfx_ids.py > src/audio/SfxIds.h

`GUN_RIFLE7BIG_1_SFX` becomes `kSfxGunRifle7big1`; the numbers are the sound's
index in the sound-effect bank (the packer's `audio/sfx_names` order).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "o2r_packer"))
from ge_audio import parse_sfx_names  # noqa: E402


def constant(name: str) -> str:
    if name.endswith("_SFX"):
        name = name[: -len("_SFX")]
    return "kSfx" + "".join(part.capitalize() for part in name.split("_"))


def main() -> None:
    header = (ROOT / "external" / "007" / "src" / "bondconstants.h").read_text()
    names = parse_sfx_names(header)
    seen = {}
    lines = []
    for index, name in enumerate(names):
        ident = constant(name)
        if ident in seen:
            raise SystemExit(f"{name} and {seen[ident]} both map to {ident}")
        seen[ident] = name
        lines.append(f"    {ident} = {index},")
    print("// Generated by tools/gen_sfx_ids.py from the GoldenEye decomp's SFX_ID enum.")
    print("#pragma once")
    print()
    print("#include <cstdint>")
    print()
    print("namespace Frigate::AudioDriver {")
    print()
    print("// SFX_ID: the sound-effect numbers the game plays sounds by (0 is no sound).")
    print("enum SfxId : int16_t {")
    print("\n".join(lines))
    print(f"    kSfxCount = {len(names)},")
    print("};")
    print()
    print("} // namespace Frigate::AudioDriver")


main()
